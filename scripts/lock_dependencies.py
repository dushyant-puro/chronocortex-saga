"""Explicit maintenance operation: regenerate both reviewed dependency locks.

Requires the separate requirements/locking.txt environment. Normal installation
and CI never resolve or update a lock. No provider configuration is read here.
"""
import argparse
from datetime import datetime, timezone
import importlib.metadata
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from scripts.dependency_audit import ROOT, UV_VERSION, INPUTS, LOCKS, MANIFEST, OPTIONS, digest, parse_lock, load_locks, selected
from packaging.markers import default_environment


def generate(*, upgrade=False):
    if importlib.metadata.version("uv") != UV_VERSION:
        raise ValueError("Pinned maintenance resolver required")
    tools = selected(parse_lock((ROOT / "requirements/locking.txt").read_text(), require_policy=False), default_environment())
    if any(importlib.metadata.version(name) != version for name, version in tools.items()):
        raise ValueError("Pinned maintenance tool versions required")
    previous = ROOT / MANIFEST
    if previous.exists() and not upgrade:
        cutoff = json.loads(previous.read_text())["resolver"]["cutoff"]
    else:
        cutoff = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    # Initial bootstrap may preserve a previously tested snapshot. Subsequent
    # refreshes use committed output pins as uv preferences, never live installs.
    env = {key: value for key, value in os.environ.items() if not key.startswith(("UV_", "PIP_"))}
    with tempfile.TemporaryDirectory(prefix="ccs-lock-generation-") as directory:
        temporary = Path(directory)
        outputs = {}
        for profile, target in LOCKS.items():
            destination = temporary / target
            existing = ROOT / target
            if existing.exists():
                shutil.copyfile(existing, destination)
            command = [sys.executable, "-m", "uv", "pip", "compile", "requirements/" + profile + ".in",
                       "--universal", "--python-version", "3.13", "--generate-hashes", "--no-build",
                       "--no-header", "--no-annotate", "--no-strip-markers", "--no-config", "--no-progress",
                       "--no-python-downloads", "--python", sys.executable, "--default-index", "https://pypi.org/simple",
                       "--exclude-newer", cutoff, "--output-file", str(destination)]
            if profile == "browser":
                command += ["--constraint", str(temporary / LOCKS["runtime"])]
            if upgrade:
                command.append("--upgrade")
            result = subprocess.run(command, cwd=ROOT, env=env, capture_output=True, text=True, timeout=300)
            if result.returncode:
                raise ValueError("Lock resolution failed; committed files preserved")
            text = destination.read_text(encoding="utf-8")
            # uv may repeat policy flags copied from a prior output. Rebuild
            # the permitted header and validate every requirement/hash below.
            text = "\n".join(line for line in text.splitlines() if line.strip() not in OPTIONS) + "\n"
            parse_lock(text, require_policy=False)
            header = "# Generated by python -m scripts.lock_dependencies; edit requirements/*.in.\n"
            text = header + "\n".join(sorted(OPTIONS)) + "\n\n" + text
            destination.write_text(text, encoding="utf-8", newline="\n")
            outputs[target] = digest(destination)
        manifest = {"schema": 1, "python_series": "3.13", "targets": ["win32/AMD64", "linux/x86_64"],
                    "resolver": {"name": "uv", "version": UV_VERSION, "index": "https://pypi.org/simple", "cutoff": cutoff},
                    "inputs": {path: digest(ROOT / path) for path in INPUTS}, "locks": outputs}
        # Validate the complete candidate bundle before touching committed locks.
        for path in INPUTS:
            (temporary / path).parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(ROOT / path, temporary / path)
        (temporary / MANIFEST).write_text(json.dumps(manifest, sort_keys=True, indent=2) + "\n", encoding="utf-8")
        load_locks(temporary)
        for target in (*LOCKS.values(), MANIFEST):
            # Same-directory replacement: a cross-volume temp directory must
            # not weaken publication. Manifest goes last; partial bundles fail audit.
            pending = None
            try:
                with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="\n",
                                                 dir=(ROOT / target).parent, delete=False) as stream:
                    pending = Path(stream.name)
                    stream.write((temporary / target).read_text(encoding="utf-8"))
                    stream.flush()
                    os.fsync(stream.fileno())
                os.replace(pending, ROOT / target)
            finally:
                if pending is not None:
                    pending.unlink(missing_ok=True)
        load_locks(ROOT)


def main():
    parser = argparse.ArgumentParser(description=__doc__, allow_abbrev=False)
    parser.add_argument("--upgrade", action="store_true", help="Advance cutoff and deliberately re-resolve; review the complete diff")
    args = parser.parse_args()
    try:
        generate(upgrade=args.upgrade)
    except Exception:
        parser.exit(1, "Lock generation failed. Inspect the input diff and preserve existing locks; no automatic fallback.\n")
    print("Both dependency locks and their manifest regenerated. Review and test before committing.")


if __name__ == "__main__":
    main()
